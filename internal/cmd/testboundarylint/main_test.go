// The approved boundary table is the oracle: fixtures may share tags, behavior
// must name one level, and unit tests need no selector.
func TestCheckFile(t *testing.T) {
	t.Parallel()
	const behavior = "package sample\nimport \"testing\"\nfunc TestBehavior(t *testing.T) {}\n"
	const fixture = "package sample\nfunc builder() {}\n"
	cases := []struct {
		name   string
		path   string
		source string
		want   string
	}{
		{name: "unit", path: "owner_test.go", source: behavior},
		{name: "integration", path: "owner_integration_test.go", source: "//go:build integration\n\n" + behavior},
		{name: "e2e", path: "owner_e2e_test.go", source: "//go:build e2e\n\n" + behavior},
		{name: "missing tag", path: "owner_integration_test.go", source: behavior, want: "same single level"},
		{
			name:   "missing suffix",
			path:   "owner_test.go",
			source: "//go:build integration\n\n" + behavior,
			want:   "same single level",
		},
		{
			name:   "wrong level",
			path:   "owner_e2e_test.go",
			source: "//go:build integration\n\n" + behavior,
			want:   "same single level",
		},
		{
			name:   "shared behavior",
			path:   "owner_integration_test.go",
			source: "//go:build integration || e2e\n\n" + behavior,
			want:   "same single level",
		},
		{name: "plain builder", path: "helpers_test.go", source: fixture},
		{name: "integration fixture", path: "helpers_test.go", source: "//go:build integration\n\n" + fixture},
		{name: "e2e fixture", path: "helpers_test.go", source: "//go:build e2e\n\n" + fixture},
		{name: "shared fixture", path: "helpers_test.go", source: "//go:build e2e || integration\n\n" + fixture},
		{name: "fixture suffix does not declare behavior", path: "helpers_integration_test.go", source: fixture},
		{
			name:   "setup",
			path:   "setup_test.go",
			source: "//go:build integration || e2e\n\npackage sample\nimport \"testing\"\nfunc TestMain(m *testing.M) {}\n",
		},
		{
			name:   "benchmark",
			path:   "owner_test.go",
			source: "//go:build integration\n\npackage sample\nimport \"testing\"\nfunc BenchmarkOwner(b *testing.B) {}\n",
			want:   "same single level",
		},
		{
			name:   "example",
			path:   "owner_test.go",
			source: "//go:build e2e\n\npackage sample\nfunc ExampleOwner() {}\n",
			want:   "same single level",
		},
		{
			name:   "fuzz is behavior",
			path:   "owner_test.go",
			source: "//go:build integration\n\npackage sample\nimport \"testing\"\nfunc FuzzOwner(f *testing.F) {}\n",
			want:   "same single level",
		},
		{
			name:   "ordinary function",
			path:   "helpers_test.go",
			source: "//go:build integration || e2e\n\npackage sample\nfunc Testhelper() {}\n",
		},
		{
			name:   "comment is not tag",
			path:   "owner_test.go",
			source: "// Test integration and e2e behavior.\n" + behavior,
		},
		{
			name:   "generated naming",
			path:   "zz_generated_test.go",
			source: "//go:build integration\n\n// Code generated by sample. DO NOT EDIT.\n\n" + behavior,
		},
		{
			name:   "malformed",
			path:   "owner_test.go",
			source: "//go:build integration &&\n\n" + behavior,
			want:   "invalid build constraint",
		},
		{
			name:   "platform extension required",
			path:   "owner_integration_test.go",
			source: "//go:build integration && linux\n\n" + behavior,
			want:   "expected integration",
		},
		{
			name:   "no unit tag",
			path:   "owner_test.go",
			source: "//go:build unit\n\n" + behavior,
			want:   "expected integration",
		},
		{
			name:   "duplicate constraint",
			path:   "owner_integration_test.go",
			source: "//go:build integration\n//go:build integration\n\n" + behavior,
			want:   "at most one",
		},
		{
			name:   "late constraint",
			path:   "owner_integration_test.go",
			source: behavior + "//go:build integration\n",
			want:   "must precede package",
		},
		{
			name:   "matching legacy",
			path:   "owner_integration_test.go",
			source: "//go:build integration\n// +build integration\n\n" + behavior,
		},
		{
			name:   "legacy mismatch",
			path:   "owner_integration_test.go",
			source: "//go:build integration\n// +build e2e\n\n" + behavior,
			want:   "legacy build constraint",
		},
		{name: "invalid Go", path: "owner_test.go", source: "not Go", want: "parse Go source"},
	}
	for _, test := range cases {
		t.Run(test.name, func(t *testing.T) {
			t.Parallel()
			problems := checkFile(test.path, []byte(test.source))
			if test.want == "" {
				if len(problems) != 0 {
					t.Fatalf("unexpected diagnostics: %+v", problems)
				}
				return
			}
			for _, problem := range problems {
				if problem.path != test.path || problem.line < 1 {
					t.Fatalf("diagnostic lost source location: %+v", problem)
				}
				if strings.Contains(problem.message, test.want) {
					return
				}
			}
			t.Fatalf("diagnostics %+v do not contain %q", problems, test.want)
		})
	}
}

func TestCheckTreeReportsInvalidSourceAndAcceptsCorrection(t *testing.T) {
	t.Parallel()
	root := t.TempDir()
	path := filepath.Join(root, "owner_integration_test.go")
	const source = "package owner\nimport \"testing\"\nfunc TestOwner(t *testing.T) {}\n"
	if err := os.WriteFile(path, []byte(source), 0o600); err != nil {
		t.Fatal(err)
	}
	var output bytes.Buffer
	if err := checkTree(root, &output); err == nil {
		t.Fatal("untagged integration behavior passed repository check")
	}
	if !strings.Contains(output.String(), path+":1:") || !strings.Contains(output.String(), "same single level") {
		t.Fatalf("missing actionable diagnostic: %q", output.String())
	}
	if err := os.WriteFile(path, []byte("//go:build integration\n\n"+source), 0o600); err != nil {
		t.Fatal(err)
	}
	output.Reset()
	if err := checkTree(root, &output); err != nil || output.Len() != 0 {
		t.Fatalf("corrected tree: error %v, diagnostics %q", err, output.String())
	}
}
